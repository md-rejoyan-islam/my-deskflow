//! Translation between Windows virtual key codes and our HID-based
//! [`inputsync_core::KeyCode`] enum.

use inputsync_core::KeyCode;
use windows::Win32::UI::Input::KeyboardAndMouse::*;

pub fn vk_to_keycode(vk: VIRTUAL_KEY) -> KeyCode {
    match vk {
        VK_A => KeyCode::A,
        VK_B => KeyCode::B,
        VK_C => KeyCode::C,
        VK_D => KeyCode::D,
        VK_E => KeyCode::E,
        VK_F => KeyCode::F,
        VK_G => KeyCode::G,
        VK_H => KeyCode::H,
        VK_I => KeyCode::I,
        VK_J => KeyCode::J,
        VK_K => KeyCode::K,
        VK_L => KeyCode::L,
        VK_M => KeyCode::M,
        VK_N => KeyCode::N,
        VK_O => KeyCode::O,
        VK_P => KeyCode::P,
        VK_Q => KeyCode::Q,
        VK_R => KeyCode::R,
        VK_S => KeyCode::S,
        VK_T => KeyCode::T,
        VK_U => KeyCode::U,
        VK_V => KeyCode::V,
        VK_W => KeyCode::W,
        VK_X => KeyCode::X,
        VK_Y => KeyCode::Y,
        VK_Z => KeyCode::Z,
        VK_0 => KeyCode::Num0,
        VK_1 => KeyCode::Num1,
        VK_2 => KeyCode::Num2,
        VK_3 => KeyCode::Num3,
        VK_4 => KeyCode::Num4,
        VK_5 => KeyCode::Num5,
        VK_6 => KeyCode::Num6,
        VK_7 => KeyCode::Num7,
        VK_8 => KeyCode::Num8,
        VK_9 => KeyCode::Num9,
        VK_RETURN => KeyCode::Enter,
        VK_ESCAPE => KeyCode::Escape,
        VK_BACK => KeyCode::Backspace,
        VK_TAB => KeyCode::Tab,
        VK_SPACE => KeyCode::Space,
        VK_OEM_MINUS => KeyCode::Minus,
        VK_OEM_PLUS => KeyCode::Equals,
        VK_OEM_4 => KeyCode::LeftBracket,
        VK_OEM_6 => KeyCode::RightBracket,
        VK_OEM_5 => KeyCode::Backslash,
        VK_OEM_1 => KeyCode::Semicolon,
        VK_OEM_7 => KeyCode::Apostrophe,
        VK_OEM_3 => KeyCode::Grave,
        VK_OEM_COMMA => KeyCode::Comma,
        VK_OEM_PERIOD => KeyCode::Period,
        VK_OEM_2 => KeyCode::Slash,
        VK_CAPITAL => KeyCode::CapsLock,
        VK_F1 => KeyCode::F1,
        VK_F2 => KeyCode::F2,
        VK_F3 => KeyCode::F3,
        VK_F4 => KeyCode::F4,
        VK_F5 => KeyCode::F5,
        VK_F6 => KeyCode::F6,
        VK_F7 => KeyCode::F7,
        VK_F8 => KeyCode::F8,
        VK_F9 => KeyCode::F9,
        VK_F10 => KeyCode::F10,
        VK_F11 => KeyCode::F11,
        VK_F12 => KeyCode::F12,
        VK_SNAPSHOT => KeyCode::PrintScreen,
        VK_SCROLL => KeyCode::ScrollLock,
        VK_PAUSE => KeyCode::Pause,
        VK_INSERT => KeyCode::Insert,
        VK_HOME => KeyCode::Home,
        VK_PRIOR => KeyCode::PageUp,
        VK_DELETE => KeyCode::Delete,
        VK_END => KeyCode::End,
        VK_NEXT => KeyCode::PageDown,
        VK_RIGHT => KeyCode::ArrowRight,
        VK_LEFT => KeyCode::ArrowLeft,
        VK_DOWN => KeyCode::ArrowDown,
        VK_UP => KeyCode::ArrowUp,
        VK_LCONTROL => KeyCode::LeftCtrl,
        VK_LSHIFT => KeyCode::LeftShift,
        VK_LMENU => KeyCode::LeftAlt,
        VK_LWIN => KeyCode::LeftSuper,
        VK_RCONTROL => KeyCode::RightCtrl,
        VK_RSHIFT => KeyCode::RightShift,
        VK_RMENU => KeyCode::RightAlt,
        VK_RWIN => KeyCode::RightSuper,
        _ => KeyCode::Unknown,
    }
}

